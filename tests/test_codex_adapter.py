"""Schema-grounded Codex event fixtures; these are NOT live write acceptance.

The schemas are generated by the installed official Codex CLI 0.160.0 and live
under evidence/codex-schema. No backend, filesystem change, approval, or network
is performed here. The small shape checker covers only schema constructs used
by these fixtures; it does not claim to be a general JSON Schema validator.
"""
from __future__ import annotations

import copy
import io
import json
from pathlib import Path
from types import SimpleNamespace
import unittest

from acw.adapters.codex import CodexAdapter


SCHEMA_ROOT = Path(__file__).resolve().parents[1] / "evidence" / "codex-schema" / "v2"
FIXTURE_CWD = str(Path(__file__).resolve().parent / "sandbox-codex")
FIXTURE_PATH = str(Path(FIXTURE_CWD) / "fixture-only.txt")
THREAD = "schema-fixture-thread"
TURN = "schema-fixture-turn"
PATCH = "--- a/fixture-only.txt\n+++ b/fixture-only.txt\n@@ -1 +1 @@\n-old\n+new 中文\n"


def check_shape(value, schema, document, trail="$"):
    """Validate generated fixture shapes using the required local schema parts."""
    if "$ref" in schema:
        reference = schema["$ref"]
        if not reference.startswith("#/"):
            raise AssertionError("Fixture checker requires a local schema reference")
        target = document
        for part in reference[2:].split("/"):
            target = target[part.replace("~1", "/").replace("~0", "~")]
        check_shape(value, target, document, trail)
    for alternative in schema.get("allOf", []):
        check_shape(value, alternative, document, trail)
    for keyword in ("oneOf", "anyOf"):
        if keyword in schema:
            matches = 0
            for alternative in schema[keyword]:
                try:
                    check_shape(value, alternative, document, trail)
                    matches += 1
                except AssertionError:
                    pass
            if not (matches == 1 if keyword == "oneOf" else matches >= 1):
                raise AssertionError(f"{trail}: {keyword} matched {matches} shapes")
    kinds = schema.get("type", [])
    if isinstance(kinds, str):
        kinds = [kinds]
    matches_type = {
        "object": isinstance(value, dict),
        "array": isinstance(value, list),
        "string": isinstance(value, str),
        "integer": isinstance(value, int) and not isinstance(value, bool),
        "number": isinstance(value, (int, float)) and not isinstance(value, bool),
        "boolean": isinstance(value, bool),
        "null": value is None,
    }
    if kinds and not any(matches_type[kind] for kind in kinds):
        raise AssertionError(f"{trail}: expected type {kinds}")
    if "enum" in schema and value not in schema["enum"]:
        raise AssertionError(f"{trail}: invalid enum value {value!r}")
    if isinstance(value, dict):
        for required in schema.get("required", []):
            if required not in value:
                raise AssertionError(f"{trail}: missing {required}")
        properties = schema.get("properties", {})
        for name, item in value.items():
            if name in properties:
                check_shape(item, properties[name], document, f"{trail}.{name}")
            elif schema.get("additionalProperties") is False:
                raise AssertionError(f"{trail}: unexpected {name}")
            elif isinstance(schema.get("additionalProperties"), dict):
                check_shape(item, schema["additionalProperties"], document, f"{trail}.{name}")
    if isinstance(value, list) and isinstance(schema.get("items"), dict):
        for index, item in enumerate(value):
            check_shape(item, schema["items"], document, f"{trail}[{index}]")
    if isinstance(value, (int, float)) and "minimum" in schema and value < schema["minimum"]:
        raise AssertionError(f"{trail}: value below schema minimum")


def notification(method, item=None, **payload):
    params = {"threadId": THREAD, "turnId": TURN, **payload}
    if item is not None:
        params["item"] = item
        params["startedAtMs" if method == "item/started" else "completedAtMs"] = 1791162507000
    return {"method": method, "params": params}


def file_item(status="completed", changes=None):
    return {"id": "patch-fixture", "type": "fileChange", "status": status,
            "changes": changes if changes is not None else [{"path": FIXTURE_PATH, "kind": {"type": "update"}, "diff": PATCH}]}


def command_item(status="completed", actions=None, output="fixture output\r\n", exit_code=0):
    return {"id": "read-fixture", "type": "commandExecution", "status": status,
            "command": "Get-Content -LiteralPath 'fixture-only.txt'", "cwd": FIXTURE_CWD,
            "commandActions": actions or [], "aggregatedOutput": output,
            "exitCode": exit_code, "durationMs": 17}


class CodexSchemaFixtureTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.schemas = {
            method: json.loads((SCHEMA_ROOT / filename).read_text(encoding="utf-8"))
            for method, filename in {
                "item/started": "ItemStartedNotification.json",
                "item/completed": "ItemCompletedNotification.json",
                "item/commandExecution/outputDelta": "CommandExecutionOutputDeltaNotification.json",
                "turn/diff/updated": "TurnDiffUpdatedNotification.json",
            }.items()
        }

    def setUp(self):
        self.events = []
        self.adapter = CodexAdapter(lambda kind, **payload: self.events.append((kind, payload)))
        self.adapter.session_id = THREAD

    def validate(self, event):
        schema = self.schemas[event["method"]]
        check_shape(event["params"], schema, schema)

    def dispatch(self, event):
        self.validate(event)
        untouched = copy.deepcopy(event)
        self.adapter._handle_message(event)
        self.assertEqual(event, untouched, "Adapter must not mutate its original backend event")

    def of_kind(self, kind):
        return [payload for emitted_kind, payload in self.events if emitted_kind == kind]

    def test_official_schema_rejects_missing_patch_and_invalid_read_path(self):
        malformed = notification("item/completed", file_item())
        del malformed["params"]["item"]["changes"][0]["diff"]
        with self.assertRaises(AssertionError):
            self.validate(malformed)
        malformed_read = command_item(actions=[{"type": "read", "command": "Get-Content", "name": "fixture-only.txt", "path": 42}])
        with self.assertRaises(AssertionError):
            self.validate(notification("item/completed", malformed_read))

    def test_file_change_add_update_move_delete_preserves_paths_and_patches(self):
        changes = [
            {"path": FIXTURE_PATH, "kind": {"type": "add"}, "diff": "+new file\n"},
            {"path": FIXTURE_PATH, "kind": {"type": "update", "move_path": FIXTURE_PATH + ".moved"}, "diff": PATCH},
            {"path": FIXTURE_PATH + ".old", "kind": {"type": "delete"}, "diff": "-old file\n"},
        ]
        event = notification("item/completed", file_item(changes=changes))
        self.dispatch(event)
        self.assertEqual([(f["path"], f["action"]) for f in self.of_kind("file")], [(c["path"], c["kind"]) for c in changes])
        self.assertEqual([d["content"] for d in self.of_kind("diff")], [c["diff"] for c in changes])
        self.assertTrue(all(d["diff"] == d["content"] for d in self.of_kind("diff")))
        self.assertEqual(self.of_kind("raw")[0]["raw"], event)

    def test_patch_lifecycle_distinguishes_proposal_from_completed_write_event(self):
        self.dispatch(notification("item/started", file_item(status="inProgress")))
        self.dispatch(notification("item/completed", file_item()))
        proposed, completed = self.of_kind("file")
        self.assertEqual((proposed["status"], completed["status"]), ("inProgress", "completed"))
        self.assertIsNone(proposed["completed"])
        self.assertIsNotNone(completed["completed"])
        self.assertEqual(proposed["started"], completed["started"])
        self.assertEqual(completed["item_id"], "patch-fixture")
        self.assertEqual(self.of_kind("raw")[0]["raw"]["params"]["startedAtMs"], 1791162507000)
        self.assertEqual(self.of_kind("raw")[1]["raw"]["params"]["completedAtMs"], 1791162507000)

    def test_declined_file_change_remains_declined_and_does_not_claim_success(self):
        self.dispatch(notification("item/completed", file_item(status="declined")))
        self.assertEqual([f["status"] for f in self.of_kind("file")], ["declined"])
        self.assertEqual([d["status"] for d in self.of_kind("diff")], ["declined"])
        self.assertEqual(self.of_kind("command"), [])

    def test_command_read_action_maps_to_read_event_with_original_path(self):
        read = {"type": "read", "command": "Get-Content -LiteralPath 'fixture-only.txt'", "name": "fixture-only.txt", "path": FIXTURE_PATH}
        event = notification("item/completed", command_item(actions=[read]))
        self.dispatch(event)
        file_event = self.of_kind("file")[0]
        self.assertEqual((file_event["path"], file_event["action"], file_event["status"]), (FIXTURE_PATH, "read", "completed"))
        self.assertEqual(self.of_kind("raw")[0]["raw"]["params"]["item"]["commandActions"], [read])

    def test_command_output_delta_is_live_and_completed_combined_output_is_preserved(self):
        output = "fixture stdout\r\nfixture stderr\r\nUnicode 中文\n"
        self.dispatch(notification("item/commandExecution/outputDelta", itemId="read-fixture", delta=output[:8]))
        terminal = notification("item/completed", command_item(status="failed", output=output, exit_code=7))
        self.dispatch(terminal)
        fragment = self.of_kind("event")[0]
        self.assertEqual((fragment["summary"], fragment["event_type"], fragment["output_stream"]), (output[:8], "command_output", "combined"))
        raw_fragment = self.of_kind("raw")[0]["raw"]
        self.assertEqual(raw_fragment["type"], "omitted_stream_fragment")
        self.assertIn("completed sanitized message retained", raw_fragment["redaction"])
        command = self.of_kind("command")[0]
        self.assertEqual((command["output"], command["exit_code"], command["duration_ms"]), (output, 7, 17))
        self.assertEqual((command["stdout"], command["stderr"], command["output_stream"]), ("", "", "combined"))
        self.assertEqual(self.of_kind("raw")[1]["raw"], terminal)

    def test_turn_unified_diff_preserves_exact_patch_and_turn_identity(self):
        event = notification("turn/diff/updated", diff=PATCH)
        self.dispatch(event)
        self.assertEqual(self.of_kind("diff"), [{"content": PATCH, "diff": PATCH, "turn_id": TURN}])
        self.assertEqual(self.of_kind("raw")[0]["raw"], event)

    def test_real_jsonl_reader_preserves_safe_structured_event_order(self):
        events = [notification("item/completed", command_item()), notification("item/completed", file_item()), notification("turn/diff/updated", diff=PATCH)]
        for event in events:
            self.validate(event)
        # Explicit test transport: exercises the real JSONL reader without a process.
        self.adapter._process = SimpleNamespace(stdout=io.StringIO("\n".join(json.dumps(event, ensure_ascii=False) for event in events) + "\n"))
        self.adapter._closing = True
        self.adapter._read_loop()
        self.assertEqual([r["raw"] for r in self.of_kind("raw")], events)
        self.assertEqual(len(self.of_kind("command")), 1)
        self.assertEqual(len(self.of_kind("file")), 1)
        self.assertEqual(len(self.of_kind("diff")), 2)
        self.assertEqual(self.of_kind("error"), [])

    def test_jsonl_reader_reports_malformed_line_and_continues_valid_events(self):
        event = notification("item/completed", file_item())
        self.validate(event)
        self.adapter._process = SimpleNamespace(stdout=io.StringIO("invalid fixture JSON\n" + json.dumps(event) + "\n"))
        self.adapter._closing = True
        self.adapter._read_loop()
        self.assertIn("non-JSON protocol line", self.of_kind("error")[0]["content"])
        self.assertEqual(self.of_kind("raw")[0]["raw"], event)
        self.assertEqual(self.of_kind("file")[0]["status"], "completed")

    def test_secret_patch_redaction_overrides_raw_preservation_without_mutating_input(self):
        patch = PATCH + "+password=synthetic-fixture-secret\n"
        event = notification("item/completed", file_item(changes=[{"path": FIXTURE_PATH, "kind": {"type": "update"}, "diff": patch}]))
        self.dispatch(event)
        saved = json.dumps(self.events, ensure_ascii=False)
        self.assertNotIn("synthetic-fixture-secret", saved)
        self.assertIn("[REDACTED]", saved)
        self.assertIn("new 中文", saved)
        self.assertIn("synthetic-fixture-secret", event["params"]["item"]["changes"][0]["diff"])


class NativePreviewTransport(CodexAdapter):
    """Explicit test-only RPC transport; actual request/response dispatch is used."""
    def __init__(self):
        self.events, self.requests = [], []
        super().__init__(lambda kind, **payload: self.events.append((kind, payload)))
        self.cwd, self.session_id, self.state = FIXTURE_CWD, "active-workspace-session", "Connected"
        self.delay_response = False
        self.metadata_cwd = FIXTURE_CWD
        self.history_cwd = FIXTURE_CWD

    def _write(self, message):
        self.requests.append(copy.deepcopy(message))
        if self.delay_response:
            return
        if message["method"] == "thread/list":
            result = {"data": [{"id": THREAD, "cwd": FIXTURE_CWD}]}
        else:
            include = message["params"].get("includeTurns")
            thread = {"id": THREAD, "cwd": self.history_cwd if include else self.metadata_cwd}
            if include:
                thread["turns"] = [{"items": [
                    {"id": "native-user", "type": "userMessage", "content": [{"type": "text", "text": "PRIVATE_NATIVE_PROMPT"}]},
                    {"id": "native-assistant", "type": "agentMessage", "text": "PRIVATE_NATIVE_RESPONSE\npassword=synthetic-native-secret"},
                    {"id": "hidden", "type": "reasoning", "content": ["HIDDEN_NATIVE_REASONING"]},
                ]}]
            result = {"thread": thread}
        self._handle_message({"id": message["id"], "result": result})


class CodexNativePreviewTests(unittest.TestCase):
    def setUp(self):
        self.adapter = NativePreviewTransport()

    def discover(self):
        self.adapter.list_sessions()
        self.adapter.events.clear()
        self.adapter.requests.clear()

    def test_native_preview_requires_explicit_scoped_discovery(self):
        self.assertFalse(self.adapter.native_history_capability()["available"])
        with self.assertRaises(PermissionError):
            self.adapter.get_history(THREAD, native=True)
        self.assertEqual(self.adapter.requests, [])
        self.discover()
        self.assertTrue(self.adapter.native_history_capability()["available"])
        with self.assertRaises(PermissionError):
            self.adapter.get_history("undiscovered", native=True)
        self.assertEqual(self.adapter.requests, [])

    def test_preview_is_returned_sanitized_but_never_emitted_to_active_task(self):
        self.discover()
        before = (self.adapter.session_id, self.adapter.cwd, self.adapter.state)
        rows = self.adapter.get_history(THREAD, native=True, limit=1, offset=1)
        self.assertEqual(len(rows), 1)
        self.assertEqual(rows[0]["role"], "assistant")
        self.assertIn("PRIVATE_NATIVE_RESPONSE", rows[0]["content"])
        self.assertNotIn("synthetic-native-secret", rows[0]["content"])
        self.assertEqual(before, (self.adapter.session_id, self.adapter.cwd, self.adapter.state))
        self.assertEqual([r["method"] for r in self.adapter.requests], ["thread/read", "thread/read"])
        self.assertEqual([r["params"]["includeTurns"] for r in self.adapter.requests], [False, True])
        emitted = json.dumps(self.adapter.events)
        self.assertNotIn("PRIVATE_NATIVE", emitted)
        self.assertNotIn("HIDDEN_NATIVE", emitted)
        self.assertTrue(all(kind == "raw" and "no transcript persisted" in payload["raw"]["redaction"] for kind, payload in self.adapter.events))

    def test_metadata_cwd_change_prevents_full_transcript_read(self):
        self.discover()
        self.adapter.metadata_cwd = str(Path(FIXTURE_CWD).parent)
        with self.assertRaises(PermissionError):
            self.adapter.get_history(THREAD, native=True)
        self.assertEqual(len(self.adapter.requests), 1)
        self.assertFalse(self.adapter.requests[0]["params"]["includeTurns"])

    def test_full_response_cwd_change_is_rejected_without_raw_leak(self):
        self.discover()
        self.adapter.history_cwd = str(Path(FIXTURE_CWD).parent)
        with self.assertRaises(PermissionError):
            self.adapter.get_history(THREAD, native=True)
        self.assertNotIn("PRIVATE_NATIVE", json.dumps(self.adapter.events))

    def test_private_timeout_still_suppresses_late_response(self):
        self.adapter.delay_response = True
        with self.assertRaises(TimeoutError):
            self.adapter._request("thread/read", {"threadId": THREAD, "includeTurns": True}, timeout=0.001, suppress_raw=True)
        request_id = self.adapter.requests[0]["id"]
        self.assertIn(request_id, self.adapter._private_request_ids)
        self.adapter._handle_message({"id": request_id, "result": {"thread": {"turns": ["LATE_PRIVATE_TRANSCRIPT"]}}})
        self.assertNotIn("LATE_PRIVATE_TRANSCRIPT", json.dumps(self.adapter.events))
        self.assertNotIn(request_id, self.adapter._private_request_ids)

    def test_default_history_keeps_existing_raw_behavior_and_invalid_bounds_do_not_read(self):
        result = self.adapter.get_history(THREAD)
        self.assertTrue(result)
        self.assertIn("PRIVATE_NATIVE_RESPONSE", json.dumps(self.adapter.events))
        self.assertNotIn("synthetic-native-secret", json.dumps(self.adapter.events))
        self.adapter.requests.clear()
        for bounds in ({"limit": 501}, {"limit": True}, {"offset": -1}, {"offset": 10001}):
            with self.assertRaises(ValueError):
                self.adapter.get_history(THREAD, native=True, **bounds)
        self.assertEqual(self.adapter.requests, [])


